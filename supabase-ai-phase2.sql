-- ============================================================================
-- 山商信息通 · AI 校园助手第二阶段（知识来源、知识切片、向量检索、未回答问题）
-- 执行方式：Supabase Dashboard -> SQL Editor -> New query -> Run
-- 特点：增量迁移，不删除第一阶段已有的 knowledge_documents 数据。
-- 向量模型：text-embedding-v4，固定使用 1024 维。
